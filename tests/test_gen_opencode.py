def test_template_permission_allow_list():
    p = _template()["permission"]
    assert next(iter(p)) == "*" and p["*"] == "deny"       # 마지막 규칙이 이긴다: 허용 목록은 맨 앞 deny
    for tool in ("task", "webfetch", "websearch", "codesearch", "question", "jira_*", "github_*"):
        assert p[tool] == "deny", tool
    assert not [k for k in p if k.startswith("jira_") and p[k] != "deny"]   # O2b(마스킹) 전에는 Jira 도구 전부 deny
    assert p["read"]["*"] == "allow" and p["glob"] == p["grep"] == p["list"] == "allow"
    bash = p["bash"]
    assert next(iter(bash)) == "*" and bash["*"] == "deny"     # bash도 허용 목록(계획 I 2단계 리뷰 P0: 간접 push)
    allows = [k for k, v in bash.items() if v == "allow"]
    assert {"python3 *", "cat *", "ls *", "grep *"} <= set(allows)
    assert not [k for k in allows if k.split()[0] in ("sh", "bash", "node", "opencode", "claude", "rm", "sed", "gh")]
    keys = list(bash)
    assert all(bash[k] == "deny" and keys.index(k) > max(keys.index(a) for a in allows) for k in WRITE_BASH)
    ext = p["external_directory"]
    assert list(ext) == ["*", "@@PLUGIN_ROOT@@/**", "@@WORK_ROOT@@/**", "@@ISSUE_DB_ROOT@@/**"]
    assert ext["*"] == "deny" and ext["@@PLUGIN_ROOT@@/**"] == ext["@@WORK_ROOT@@/**"] == "allow"
    edit = p["edit"]
    keys = list(edit)
    assert keys[0] == "*" and edit["*"] == "deny" and edit["@@WORK_ROOT_REL@@/**"] == "allow"
    for deny in ("@@ISSUE_DB_ROOT_REL@@/**", "@@PLUGIN_ROOT_REL@@/**", "**/.opencode/**", "**/opencode.json",
                 "**/AGENTS.md", "**/tt-oc.json"):
        assert edit[deny] == "deny" and keys.index(deny) > keys.index("@@WORK_ROOT_REL@@/**"), deny


def test_managed_sample():
    m = json.loads(MANAGED.read_text(encoding="utf-8"))
    assert set(m) <= V1_KEYS
    assert m["snapshot"] is False and m["autoupdate"] is False and m["share"] == "disabled"
    p = m["permission"]
    assert p["task"] == p["jira_*"] == p["github_*"] == p["webfetch"] == "deny"
    assert "*" not in p["bash"]           # 프로젝트 설정의 bash 허용 목록 뒤에 붙어 deny가 이긴다(관리 설정이 나중에 합쳐진다)
    tmpl_denies = {k for k, v in _template()["permission"]["bash"].items() if v == "deny" and k != "*"}
    assert tmpl_denies <= {k for k, v in p["bash"].items() if v == "deny"}
    # 배포된 관리 설정 비교(site_step.py runtime-check opencode, O10): 예시 그대로면 문제 없음, 빠진 deny·다른 값은 문제
    assert gen_opencode.managed_problems(m) == [] and gen_opencode.managed_problems([]) == ["객체가 아니다"]
    worse = json.loads(MANAGED.read_text(encoding="utf-8"))
    worse["snapshot"] = True
    worse["permission"]["task"] = "allow"
    del worse["permission"]["bash"]["*module_eval.py*"]
    worse["permission"]["more"] = "deny"                      # 더 막는 것은 괜찮다
    assert gen_opencode.managed_problems(worse) == ["snapshot=true(필요 false)", "permission['task']=\"allow\"(필요 \"deny\")",
                                                    "permission.bash['*module_eval.py*'] 없음"]


