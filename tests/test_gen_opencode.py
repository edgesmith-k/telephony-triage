# -- 실제 opencode 1.19.5로 읽어 보기(있을 때만) -------------------------------------------------------------------------

def _opencode():
    oc = os.environ.get("TT_OPENCODE") or shutil.which("opencode")
    if not oc or not Path(oc).exists():
        pytest.skip("opencode가 설치되지 않았다(TT_OPENCODE 또는 PATH)")
    return oc


def _oc_env(home: Path) -> dict:
    keep = {k: v for k, v in os.environ.items() if k in ("PATH", "LANG", "TMPDIR")}
    return {**keep, "HOME": str(home), "XDG_CONFIG_HOME": str(home / ".config"), "XDG_DATA_HOME": str(home / ".data"),
            "XDG_CACHE_HOME": str(home / ".cache"), "XDG_STATE_HOME": str(home / ".state"),
            "OPENCODE_DISABLE_AUTOUPDATE": "1", "OPENCODE_DISABLE_MODELS_FETCH": "1", "NO_PROXY": "127.0.0.1,localhost"}


def test_installed_config_loads_in_opencode(roots):
    oc = _opencode()
    env = _oc_env(roots / "home")
    ver = subprocess.run([oc, "--version"], env=env, stdin=subprocess.DEVNULL, capture_output=True, text=True,
                         timeout=60, check=False).stdout.strip()
    if ver != gen_opencode.OPENCODE_VERSION:
        pytest.fail(f"opencode {ver} ≠ 고정 {gen_opencode.OPENCODE_VERSION} — 버전 불일치는 보고한다")
    assert _install(roots, "--issue-db", str(roots / "dbA")).returncode == 0
    proj = roots / "proj"
    r = subprocess.run([oc, "debug", "config"], cwd=proj, env=env, stdin=subprocess.DEVNULL, capture_output=True,
                       text=True, timeout=120, check=False)
    assert r.returncode == 0, r.stderr[-2000:]
    cfg = json.loads(r.stdout)
    assert cfg["snapshot"] is False and cfg["share"] == "disabled" and cfg["permission"]["*"] == "deny"
    assert sorted(cfg["command"]) == sorted(p.stem for p in (OC / "commands").glob("*.md"))
    r = subprocess.run([oc, "debug", "agent", "triage"], cwd=proj, env=env, stdin=subprocess.DEVNULL,
                       capture_output=True, text=True, timeout=120, check=False)
    assert r.returncode == 0, r.stderr[-2000:]
    agent = json.loads(r.stdout)
    assert agent["mode"] == "primary" and agent["steps"] == yaml.safe_load(AGENT.read_text(encoding="utf-8").split("---")[1])["steps"]
    assert agent["tools"].get("task") is False and agent["tools"].get("skill") is False
    rules = [(x["permission"], x["pattern"], x["action"]) for x in agent["permission"]]
    assert ("edit", f"{str(roots).lstrip('/')}/work/**", "allow") in rules
