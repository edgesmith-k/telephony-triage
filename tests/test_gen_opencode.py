def test_every_plugin_command_classified_and_generated():
    names = sorted(p.stem for p in (REPO / "plugin" / "commands").glob("*.md"))
    assert sorted((*gen_opencode.READ_FLOWS, *gen_opencode.WRITE_FLOWS)) == names
    assert not set(gen_opencode.READ_FLOWS) & set(gen_opencode.WRITE_FLOWS)
    assert sorted(p.name for p in (OC / "commands").glob("*.md")) == sorted(f"tt-{n}.md" for n in names)


@pytest.mark.parametrize("name", sorted(p.stem for p in (REPO / "plugin" / "commands").glob("*.md")))
def test_generated_command_shape(name):
    text = (OC / "commands" / f"tt-{name}.md").read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n", text, re.DOTALL)
    meta = yaml.safe_load(m.group(1))
    assert set(meta) == {"description", "agent"} and meta["agent"] == "triage" and meta["description"]
    assert "${CLAUDE_PLUGIN_ROOT}" not in text and "/telephony-triage:" not in text
    assert "@@PLUGIN_ROOT@@" in text or name == "help"
    if name in gen_opencode.WRITE_FLOWS:
        assert "OpenCode v1 — 분석 전용." in text and gen_opencode.WRITE_FLOWS[name] in text
        assert "OpenCode v1에서는 실행하지 않습니다." in text
    else:
        assert "분석 전용." not in text


def test_convert_synthetic_command():
    src = ("---\ndescription: 예시 커맨드\nargument-hint: \"<KEY>\"\n---\n\n"
           "`${CLAUDE_PLUGIN_ROOT}/x.md`를 읽는다. `/telephony-triage:help`. 인자: $ARGUMENTS\n")
    out = gen_opencode.convert("analyze", src)
    assert out.startswith("---\n# generated by tools/gen_opencode.py from plugin/commands/analyze.md")
    assert 'description: "예시 커맨드"\nagent: triage\n---\n' in out
    assert "인자 형식: `/tt-analyze <KEY>`" in out
    assert "`@@PLUGIN_ROOT@@/x.md`를 읽는다. `/tt-help`. 인자: $ARGUMENTS" in out
    with pytest.raises(gen_opencode.UsageError):
        gen_opencode.convert("x", "no frontmatter\n")


