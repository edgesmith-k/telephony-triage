def _install(root: Path, *extra, dest="proj"):
    return run_gen("install", "--dest", str(root / dest), "--plugin-root", str(root / "plug"), "--work-root",
                   str(root / "work"), "--gateway-url", "http://localhost:9/v1", "--model", "glm-x", *extra)


def test_install_renders_everything(roots):
    r = _install(roots, "--issue-db", str(roots / "dbA"), "--issue-db", str(roots / "dbB"))
    assert r.returncode == 0, r.stderr
    proj = roots / "proj"
    files = [p for p in proj.rglob("*") if p.is_file()]
    assert not [p for p in files if "@@" in p.read_text(encoding="utf-8")]
    cfg = json.loads((proj / "opencode.json").read_text(encoding="utf-8"))
    rel = str(roots).lstrip("/")
    assert list(cfg["permission"]["edit"])[:5] == ["*", f"{rel}/work/**", f"{rel}/dbA/**", f"{rel}/dbB/**", f"{rel}/plug/**"]
    assert list(cfg["permission"]["external_directory"]) == ["*", f"{roots}/plug/**", f"{roots}/work/**", f"{roots}/dbA/**",
                                                             f"{roots}/dbB/**"]
    assert cfg["model"] == "gw/glm-x" and cfg["provider"]["gw"]["options"]["baseURL"] == "http://localhost:9/v1"
    meta = json.loads((proj / "tt-oc.json").read_text(encoding="utf-8"))
    integrity = meta.pop("integrity")
    assert meta == {"version": 1, "opencode": "1.19.5", "plugin_root": str(roots / "plug"), "work_root": str(roots / "work"),
                    "issue_dbs": [str(roots / "dbA"), str(roots / "dbB")], "model": "glm-x"}
    # 설치 지문(리뷰 P1: guard 플러그인 삭제·adapter 수정을 tt-oc doctor가 찾는다): tt-oc.json 말고 설치한 모든 파일
    assert set(integrity["files"]) == {p.relative_to(proj).as_posix() for p in files if p.name != "tt-oc.json"}
    assert ".opencode/plugins/tt-guard.js" in integrity["files"] and "opencode.json" in integrity["files"]
    assert all(integrity["files"][p.relative_to(proj).as_posix()] == hashlib.sha256(p.read_bytes()).hexdigest()
               for p in files if p.name != "tt-oc.json")
    assert integrity["plugin_scripts"] == gen_opencode.scripts_digest(roots / "plug")
    agent = (proj / ".opencode" / "agents" / "triage.md").read_text(encoding="utf-8")
    assert f"Plugin root: `{roots / 'plug'}`" in agent
    analyze = (proj / ".opencode" / "commands" / "tt-analyze.md").read_text(encoding="utf-8")
    assert f"{roots / 'plug'}/skills/telephony-triage/SKILL.md" in analyze
    assert len(list((proj / ".opencode" / "commands").glob("tt-*.md"))) == 14
    guard_js = (proj / ".opencode" / "plugins" / "tt-guard.js").read_text(encoding="utf-8")   # 1.19.5가 자동으로 싣는 폴더
    assert f'const INSTALLED_ROOT = "{roots / "plug"}"' in guard_js
    assert _install(roots, "--issue-db", str(roots / "dbA"), "--issue-db", str(roots / "dbB")).returncode == 0   # 같으면 다시 써도 된다


