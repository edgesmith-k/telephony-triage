MANAGED_NAMES = ("opencode.json", "opencode.jsonc")


def managed_problems(cfg) -> list[str]:
    """배포된 관리 설정이 `managed.json.sample`의 막는 항목을 모두 갖는지: 최상위 snapshot·autoupdate·share는 같은 값,
    permission의 deny(bash 패턴 포함)는 모두 deny. 다른 키를 더한 것은 문제가 아니다(사내가 더 막을 수 있다)."""
    want = json.loads(MANAGED_SAMPLE.read_text(encoding="utf-8"))
    if not isinstance(cfg, dict):
        return ["객체가 아니다"]
    out = [f"{k}={json.dumps(cfg.get(k))}(필요 {json.dumps(want[k])})"
           for k in ("snapshot", "autoupdate", "share") if k in want and cfg.get(k) != want[k]]
    have = cfg.get("permission") if isinstance(cfg.get("permission"), dict) else {}
    for key, value in want.get("permission", {}).items():
        if isinstance(value, dict):
            sub = have.get(key) if isinstance(have.get(key), dict) else {}
            out += [f"permission.{key}[{pat!r}] 없음" for pat, v in value.items() if v == "deny" and sub.get(pat) != "deny"]
        elif value == "deny" and have.get(key) != "deny":
            out.append(f"permission[{key!r}]={json.dumps(have.get(key))}(필요 \"deny\")")
    return out


def scripts_digest(plugin_root: Path) -> str:
    """플러그인 스크립트(`scripts/**/*.py`) 전체의 지문. `opencode/bin/tt-oc` `scripts_digest`와 같은 계산이다."""
    h = hashlib.sha256()
    base = plugin_root / "scripts"
    for p in sorted(base.rglob("*.py")):
        if "__pycache__" in p.parts or not p.is_file():
            continue
        h.update(f"{p.relative_to(base).as_posix()}\0{hashlib.sha256(p.read_bytes()).hexdigest()}\n".encode())
    return h.hexdigest()


def cmd_install(a) -> int:
    plugin = _abs_dir(a.plugin_root, "--plugin-root")
    if not (Path(plugin) / "scripts" / "guard.py").is_file():
        raise UsageError(f"--plugin-root에 scripts/guard.py가 없다: {plugin}")
    work = _abs_dir(a.work_root, "--work-root")
    dbs = [_abs_dir(c, "--issue-db") for c in a.issue_db or []]
    dest = Path(_abs_dir(a.dest, "--dest", must_exist=False))
    for root in (plugin, *dbs):
        if dest == Path(root) or Path(root) in dest.parents:
            raise UsageError(f"--dest는 플러그인·이슈 DB clone 밖이어야 한다: {dest}")
    if git_root(dest):
        raise UsageError(f"--dest가 git 레포({git_root(dest)}) 안이다 — edit 권한 패턴이 맞지 않는다. git 레포 밖 폴더를 쓴다.")
    if not re.fullmatch(r"https?://[^\s\"]+", a.gateway_url):
        raise UsageError(f"--gateway-url 형식: http(s)://…: {a.gateway_url}")
    if not re.fullmatch(r"[A-Za-z0-9._:/-]+", a.model):
        raise UsageError(f"--model 형식: 영문·숫자·._:/- : {a.model}")
    values = {"@@PLUGIN_ROOT@@": plugin, "@@WORK_ROOT@@": work, "@@PLUGIN_ROOT_REL@@": _rel(plugin),
              "@@WORK_ROOT_REL@@": _rel(work), "@@GATEWAY_BASE_URL@@": a.gateway_url, "@@MODEL_ID@@": a.model}
    jira_read = list(dict.fromkeys(a.jira_read_tool or []))
    bad = jira_read_problems(jira_read)
    if bad:
        raise UsageError("; ".join(bad))
    files = install_files(dest, values, dbs, read_roots(plugin), jira_read)
    differ = [str(p) for p, text in files.items() if p.exists() and p.read_text(encoding="utf-8") != text]
    if differ and not a.force:
        raise UsageError(f"이미 있는 파일과 다르다(--force로 덮어쓴다): {differ}")
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    print(json.dumps({"ok": True, "dest": str(dest), "written": [str(p) for p in files],
                      "next": f"opencode/bin/tt-oc --project {dest} doctor"}, ensure_ascii=False))
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="gen_opencode.py", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="쓰지 않고 다르면 종료 코드 1")
    sub = ap.add_subparsers(dest="cmd")
    p = sub.add_parser("install", help="OpenCode 프로젝트 폴더에 설정·에이전트·커맨드를 쓴다")
    p.add_argument("--dest", required=True)
    p.add_argument("--plugin-root", required=True)
    p.add_argument("--work-root", required=True)
    p.add_argument("--issue-db", action="append")
    p.add_argument("--gateway-url", required=True)
    p.add_argument("--model", required=True)
    p.add_argument("--jira-read-tool", action="append",
                   help="Jira 읽기 도구의 OpenCode 이름(<서버>_<도구>)을 permission allow로 더한다(관문을 연 뒤 tt-oc에서 읽으려면)")
    p.add_argument("--force", action="store_true")
    try:
        a = ap.parse_args(argv)
    except SystemExit as exc:
        return 0 if exc.code == 0 else 2
    try:
        if a.cmd == "install":
            return cmd_install(a)
        return cmd_generate(a.check)
    except (UsageError, OSError, ValueError) as exc:
        print(json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
