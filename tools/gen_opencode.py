def _sub(s: str, values: dict) -> str:
    for k, v in values.items():
        s = s.replace(k, v)
    return s


def render_config(template, values: dict, issue_dbs: list[str]):
    """템플릿 객체의 키·값에서 자리 표시를 바꾼다. 키에 `MULTI` 자리 표시가 있으면 clone마다 펼친다(순서 유지 — 마지막 규칙이
    이긴다, 1.19.5 실험). clone이 없으면 그 키를 뺀다."""
    if isinstance(template, dict):
        out = {}
        for k, v in template.items():
            if any(m in k for m in MULTI):
                keys = [k.replace(MULTI[1], _rel(c)).replace(MULTI[0], c) for c in issue_dbs]
            else:
                keys = [_sub(k, values)]
            for key in keys:
                out[key] = render_config(v, values, issue_dbs)
        return out
    if isinstance(template, list):
        return [render_config(v, values, issue_dbs) for v in template]
    if isinstance(template, str):
        if any(m in template for m in MULTI):
            raise UsageError(f"{MULTI[0]}는 설정 키에만 쓸 수 있다: {template!r}")
        return _sub(template, values)
    return template


def _rel(path: str) -> str:
    """`edit` 권한 패턴용: OpenCode는 파일 경로를 worktree 기준 상대 경로로 맞춘다(1.19.5 `path.relative(worktree, file)`).
    git 레포가 아닌 프로젝트 폴더의 worktree는 `/`라서 절대 경로에서 앞의 `/`를 뗀 모양이 된다(실험 e1). 그래서 프로젝트 폴더는
    git 레포 안이면 안 된다(`git_root`)."""
    return path.lstrip("/")


def git_root(path: Path) -> Path | None:
    """path 또는 그 위 폴더 중 `.git`이 있는 첫 폴더(없으면 None)."""
    for d in (path, *path.parents):
        if (d / ".git").exists():
            return d
    return None


def _abs_dir(raw: str, what: str, must_exist: bool = True) -> str:
    p = Path(raw).expanduser()
    if not p.is_absolute():
        raise UsageError(f"{what}는 절대 경로여야 한다: {raw}")
    p = p.resolve()
    if must_exist and not p.is_dir():
        raise UsageError(f"{what} 폴더가 없다: {p}")
    s = str(p)
    if any(c in s for c in "\"*?[]{}\n\r") or "@@" in s:
        raise UsageError(f"{what} 경로에 쓸 수 없는 글자가 있다(\" * ? [ ] {{ }} 줄바꿈 @@): {s}")
    return s


def read_roots(plugin_root: str) -> list[str]:
    """`config.py check --roots`의 `read_roots`(플러그인 스킬 폴더·work_dir·풀린 설치 스킬 SKILL.md 폴더, B2 R21). 설치하는 사용자의
    설정으로 돈다. 읽지 못하거나 경로에 패턴 글자가 있으면 그 항목은 뺀다(예외 없음)."""
    try:
        r = subprocess.run([sys.executable, str(Path(plugin_root) / "scripts" / "config.py"), "check", "--roots"],
                           stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=60, check=False,
                           env={**os.environ, "CLAUDE_PLUGIN_ROOT": plugin_root})
        roots = json.loads(r.stdout).get("read_roots")
    except (OSError, subprocess.TimeoutExpired, ValueError, AttributeError):
        return []
    out = []
    for x in roots if isinstance(roots, list) else []:
        if isinstance(x, str) and os.path.isabs(x) and not any(c in x for c in "\"*?[]{}\n\r") and "@@" not in x:
            out.append(os.path.normpath(x))
    return list(dict.fromkeys(out))


def add_read_roots(config: dict, roots: list[str], covered: list[str]) -> dict:
    """설치 설정 `permission.external_directory`에 `<root>/**: allow`(읽기 — edit 권한은 그대로 deny)를 더한다. 이미 덮인 폴더는 뺀다."""
    ext = config.get("permission", {}).get("external_directory")
    if not isinstance(ext, dict):
        return config
    for root in roots:
        if any(root == c or root.startswith(c.rstrip("/") + "/") for c in covered):
            continue
        ext.setdefault(f"{root}/**", "allow")
    return config


JIRA_TOOL_RE = re.compile(r"[A-Za-z0-9_-]+")


def jira_read_problems(names: list[str]) -> list[str]:
    """`--jira-read-tool` 이름 검사: OpenCode 도구 이름 모양(`<서버>_<도구>`, 영문·숫자·_-)이고 쓰기로 보이지 않는다
    (`mcptools.is_write` — 코멘트·상태 전환 등은 OpenCode v1에서 늘 거부)."""
    sys.path.insert(0, str(REPO / "plugin" / "scripts"))
    from common import mcptools

    out = []
    for name in names:
        if not JIRA_TOOL_RE.fullmatch(name) or "_" not in name:
            out.append(f"--jira-read-tool 형식(<서버>_<도구>, 영문·숫자·_-): {name!r}")
        elif mcptools.is_write(name) or not mcptools.is_read(name):
            out.append(f"--jira-read-tool은 읽기 도구만: {name}")
    return out


def add_jira_reads(config: dict, names: list[str]) -> dict:
    perm = config.get("permission")
    if isinstance(perm, dict):
        for name in names:
            perm.pop(name, None)
            perm[name] = "allow"         # 끝에 둔다: `jira_*` deny 뒤(마지막 규칙이 이긴다)
    return config


def install_files(dest: Path, values: dict, issue_dbs: list[str], roots: list[str] = (),
                  jira_read: list[str] = ()) -> dict[Path, str]:
    template = json.loads((OC / "opencode.json.template").read_text(encoding="utf-8"))
    meta = {"version": 1, "opencode": OPENCODE_VERSION, "plugin_root": values["@@PLUGIN_ROOT@@"],
            "work_root": values["@@WORK_ROOT@@"], "issue_dbs": issue_dbs, "model": values["@@MODEL_ID@@"]}
    if jira_read:
        meta["jira_read_tools"] = list(jira_read)
    config = add_read_roots(render_config(template, values, issue_dbs), list(roots),
                            [values["@@PLUGIN_ROOT@@"], values["@@WORK_ROOT@@"], *issue_dbs])
    config = add_jira_reads(config, list(jira_read))
    files = {dest / "opencode.json": json.dumps(config, ensure_ascii=False, indent=2) + "\n",
             dest / "tt-oc.json": json.dumps(meta, ensure_ascii=False, indent=2) + "\n"}
    for sub in INSTALL_DIRS:
        for src in sorted((OC / sub).glob("*")) if (OC / sub).is_dir() else []:
            if src.is_file():
                files[dest / ".opencode" / sub / src.name] = _sub(src.read_text(encoding="utf-8"), values)
    left = sorted({m for text in files.values() for m in PLACEHOLDER.findall(text)})
    if left:
        raise UsageError(f"바꾸지 못한 자리 표시: {left}")
    # 설치 지문: tt-oc doctor가 비교한다(guard 플러그인이 지워지거나 adapter·guard가 고쳐진 채로 다음 세션이 도는 것을 막는다)
    meta["integrity"] = {
        "files": {p.relative_to(dest).as_posix(): hashlib.sha256(text.encode("utf-8")).hexdigest()
                  for p, text in sorted(files.items()) if p.name != "tt-oc.json"},
        "plugin_scripts": scripts_digest(Path(values["@@PLUGIN_ROOT@@"])),
    }
    files[dest / "tt-oc.json"] = json.dumps(meta, ensure_ascii=False, indent=2) + "\n"
    return files


