def _oc_version_module():
    """OpenCode 바이너리 의존 한 곳(`plugin/scripts/common/oc_version.py`)을 경로로 읽는다(sys.path는 건드리지 않는다)."""
    import importlib.util
    path = REPO / "plugin" / "scripts" / "common" / "oc_version.py"
    spec = importlib.util.spec_from_file_location("gen_oc_version", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


OPENCODE_VERSION = _oc_version_module().OPENCODE_VERSION     # = opencode/bin/tt-oc PINNED = oc_adapter.OPENCODE_VERSION


class UsageError(Exception):
    pass


def _split(text: str, name: str) -> tuple[dict, str]:
    m = re.match(r"---\n(.*?)\n---\n", text, re.DOTALL)
    if not m:
        raise UsageError(f"plugin/commands/{name}.md: frontmatter 없음")
    meta = yaml.safe_load(m.group(1)) or {}
    if not isinstance(meta, dict) or not meta.get("description"):
        raise UsageError(f"plugin/commands/{name}.md: description 없음")
    return meta, text[m.end():]


def convert(name: str, text: str) -> str:
    """Claude Code 커맨드 하나 → OpenCode 커맨드 본문(설치 전, `@@PLUGIN_ROOT@@` 그대로)."""
    meta, body = _split(text, name)
    body = body.replace("${CLAUDE_PLUGIN_ROOT}", "@@PLUGIN_ROOT@@")
    body = body.replace("/telephony-triage:", "/" + PREFIX).replace("`telephony-triage:`", f"`{PREFIX}`")
    head = ["---", GEN_MARK.format(name=name), "description: " + json.dumps(str(meta["description"]), ensure_ascii=False),
            "agent: triage", "---", ""]
    if meta.get("argument-hint"):
        head += [f"인자 형식: `/{PREFIX}{name} {meta['argument-hint']}`", ""]
    if name in WRITE_FLOWS:
        head += [NOTE.format(ops=WRITE_FLOWS[name]), ""]
    if name in WRITE_FLOWS or "TT_LOCK_OWNER" in body:
        head += [LOCK_NOTE, ""]
    return "\n".join(head) + "\n" + body.lstrip("\n")


def generate() -> dict[str, str]:
    names = sorted(p.stem for p in SRC.glob("*.md"))
    unknown = [n for n in names if n not in READ_FLOWS and n not in WRITE_FLOWS]
    stale = [n for n in (*READ_FLOWS, *WRITE_FLOWS) if n not in names]
    if unknown or stale:
        raise UsageError(f"커맨드 분류가 plugin/commands와 다르다 — 분류 없음 {unknown}, 없는 커맨드 {stale}. "
                         "tools/gen_opencode.py의 READ_FLOWS·WRITE_FLOWS를 고친다.")
    return {f"{PREFIX}{n}.md": convert(n, (SRC / f"{n}.md").read_text(encoding="utf-8")) for n in names}


def cmd_generate(check: bool) -> int:
    want = generate()
    have = {p.name: p.read_text(encoding="utf-8") for p in OUT.glob("*.md")} if OUT.is_dir() else {}
    diff = sorted(n for n in set(want) | set(have) if want.get(n) != have.get(n))
    if check:
        if diff:
            print(json.dumps({"ok": False, "differs": diff, "fix": "python3 tools/gen_opencode.py"}, ensure_ascii=False))
            return 1
        print(json.dumps({"ok": True, "files": len(want)}))
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for n in diff:
        if n in want:
            (OUT / n).write_text(want[n], encoding="utf-8", newline="\n")
        else:
            (OUT / n).unlink()
    print(json.dumps({"ok": True, "written": diff}, ensure_ascii=False))
    return 0


